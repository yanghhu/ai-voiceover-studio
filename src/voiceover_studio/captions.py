"""Styled captions: turn subtitle cues into an ASS file that ffmpeg/libass burns in.

Sizes are derived from the video height, so the same style looks right in
1920x1080, 1280x720 and vertical 1080x1920.

Styles:

* ``clean``   white text, soft dark outline and shadow, lower third (default)
* ``box``     white text on a translucent dark box
* ``bold``    large heavy yellow-and-white text in the middle, for Shorts / Reels
* ``minimal`` small, thin outline, for screen recordings
"""
from dataclasses import dataclass
from typing import Iterable, List, Optional, Tuple

from .errors import ConfigError
from .subtitles import Cue


@dataclass(frozen=True)
class CaptionStyle:
    name: str
    size: float              # font size as a fraction of video height
    primary: str             # ASS colour &HAABBGGRR
    outline_colour: str
    back_colour: str
    border_style: int        # 1 outline + shadow, 3 opaque box
    outline: float           # fraction of height
    shadow: float            # fraction of height
    alignment: int           # numpad layout: 2 bottom centre, 5 middle centre
    margin_v: float          # fraction of height
    bold: bool = True
    accent: str = "&H0044CCFF"  # speaker label colour
    uppercase: bool = False


STYLES = {
    "clean": CaptionStyle("clean", 0.054, "&H00FFFFFF", "&H28000000", "&H78000000", 1,
                          0.0034, 0.0022, 2, 0.075, accent="&H00FFE3A6"),
    "box": CaptionStyle("box", 0.046, "&H00FFFFFF", "&H70141418", "&H70141418", 3,
                        0.0110, 0.0, 2, 0.070, accent="&H0091E3FF"),
    "bold": CaptionStyle("bold", 0.085, "&H0000E5FF", "&H00000000", "&H80000000", 1,
                         0.0060, 0.0025, 5, 0.0, accent="&H00FFFFFF", uppercase=True),
    "minimal": CaptionStyle("minimal", 0.038, "&H00FFFFFF", "&H40000000", "&H00000000", 1,
                            0.0018, 0.0, 2, 0.050, bold=False),
}
DEFAULT_FONT = "Inter"


def get_style(name: str) -> CaptionStyle:
    try:
        return STYLES[name]
    except KeyError:
        raise ConfigError("Unknown caption style %r. Choose one of: %s" % (name, ", ".join(STYLES))) from None


def font_px(style: CaptionStyle, size: Tuple[int, int]) -> int:
    """Caption font size in pixels; based on the short side so vertical video stays legible."""
    return max(8, int(round(style.size * min(size))))


def line_layout(size: Tuple[int, int], style: str = "clean") -> Tuple[int, int]:
    """``(max_chars, line_width)`` for subtitle chunking at this video size, in the
    weight units of :mod:`voiceover_studio.subtitles` (a CJK character counts 2)."""
    st = get_style(style)
    usable = size[0] * 0.86
    width = max(12, int(usable / (font_px(st, size) * (0.62 if st.uppercase else 0.52))))
    width = min(width, 42)
    return width * 2, width


def ass_time(seconds: float) -> str:
    cs = int(round(max(0.0, seconds) * 100))
    h, rem = divmod(cs, 360000)
    m, rem = divmod(rem, 6000)
    s, cs = divmod(rem, 100)
    return "%d:%02d:%02d.%02d" % (h, m, s, cs)


def _escape(text: str) -> str:
    return (text.replace("\\", "\\\\").replace("{", "(").replace("}", ")")
            .replace("\r", "").replace("\n", "\\N"))


def to_ass(cues: Iterable[Cue], size: Tuple[int, int], *, style: str = "clean",
           font: Optional[str] = None, speaker_labels: bool = False,
           title: Optional[str] = None, title_seconds: float = 3.2) -> str:
    """Build an ASS document for ``cues`` at video ``size`` (width, height)."""
    st = get_style(style)
    w, h = size
    font = font or DEFAULT_FONT
    px = lambda frac: max(1, int(round(frac * min(w, h))))  # noqa: E731
    fs = font_px(st, size)
    margin_h = int(w * 0.07)
    header = [
        "[Script Info]",
        "; generated by ai-voiceover-studio",
        "ScriptType: v4.00+",
        "PlayResX: %d" % w,
        "PlayResY: %d" % h,
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "",
        "[V4+ Styles]",
        "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, "
        "Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, "
        "Shadow, Alignment, MarginL, MarginR, MarginV, Encoding",
        "Style: Caption,%s,%d,%s,&H000000FF,%s,%s,%d,0,0,0,100,100,%.1f,0,%d,%d,%d,%d,%d,%d,%d,1" % (
            font, fs, st.primary, st.outline_colour, st.back_colour, -1 if st.bold else 0, fs * 0.012,
            st.border_style, px(st.outline), px(st.shadow), st.alignment, margin_h, margin_h,
            px(st.margin_v)),
        "Style: Title,%s,%d,&H00FFFFFF,&H000000FF,&H60000000,&H80000000,-1,0,0,0,100,100,0,0,1,%d,%d,8,"
        "%d,%d,%d,1" % (font, px(0.072), px(0.004), px(0.003), margin_h, margin_h, px(0.12)),
        "",
        "[Events]",
        "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text",
    ]
    events: List[str] = []
    if title:
        events.append("Dialogue: 1,%s,%s,Title,,0,0,0,,{\\fad(400,500)}%s" % (
            ass_time(0.15), ass_time(title_seconds), _escape(title.strip())))
    label_size = max(1, int(fs * 0.62))
    for cue in cues:
        text = cue.text.strip()
        if not text:
            continue
        text = _escape(text.upper() if st.uppercase else text)
        if speaker_labels and cue.speaker:
            text = "{\\fs%d\\c%s\\bord%d}%s{\\r}\\N%s" % (
                label_size, st.accent, max(1, px(st.outline) // 2), _escape(cue.speaker.title()), text)
        events.append("Dialogue: 0,%s,%s,Caption,,0,0,0,,{\\fad(120,120)}%s" % (
            ass_time(cue.start), ass_time(cue.end), text))
    return "\n".join(header + events) + "\n"

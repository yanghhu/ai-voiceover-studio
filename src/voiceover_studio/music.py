"""Background music: a built-in generated ambient bed, or your own track, ducked under the voice.

The built-in track (``--music ambient``) is synthesized on the fly by ffmpeg's
``aevalsrc`` from the expressions below: a slow four-chord pad with a soft
plucked arpeggio. It is generated by this project at render time, so it carries
no third-party licence and needs no download.

Ducking uses ffmpeg's ``sidechaincompress``: the voice is the side chain, so the
music dips while someone speaks and swells back in the pauses.
"""
import math
from typing import List, Optional, Sequence, Tuple

BUILTIN = ("ambient", "pulse")

# Chords as MIDI notes (root, third, fifth, colour), four bars of BAR seconds each.
_PROGRESSIONS = {
    # Am9 - Fmaj7 - C(add9) - G6: calm, slightly wistful
    "ambient": ((57, 60, 64, 71), (53, 57, 60, 64), (48, 52, 55, 62), (55, 59, 62, 64)),
    # Dm7 - Bbmaj7 - F - C: a little brighter, faster arpeggio
    "pulse": ((50, 53, 57, 60), (46, 50, 53, 57), (53, 57, 60, 65), (48, 52, 55, 62)),
}
_BAR = {"ambient": 4.0, "pulse": 3.2}
_STEP = {"ambient": 0.5, "pulse": 0.4}


def _hz(note: int) -> float:
    return 440.0 * 2 ** ((note - 69) / 12.0)


def _select(index: str, values: Sequence[float]) -> str:
    """ffmpeg expression that picks ``values[index]`` (index is an expression)."""
    expr = "%.3f" % values[-1]
    for i in range(len(values) - 2, -1, -1):
        expr = "if(eq(%s,%d),%.3f,%s)" % (index, i, values[i], expr)
    return expr


def generator_expr(name: str = "ambient") -> str:
    """The ``aevalsrc`` expression of a built-in track (mono, values within -1..1)."""
    chords = _PROGRESSIONS[name]
    bar, step = _BAR[name], _STEP[name]
    chord = "mod(floor(t/%g),%d)" % (bar, len(chords))
    pos = "mod(t,%g)" % bar
    # pad envelope: fade in over 1.2 s, out over the last 0.8 s of each bar (no clicks)
    env = "min(1,%s/1.2)*min(1,(%g-%s)/0.8)" % (pos, bar, pos)
    pad = []
    for voice in range(4):
        f = _select(chord, [_hz(c[voice]) for c in chords])
        detune = 1.003 if voice % 2 else 0.997
        pad.append("sin(2*PI*%s*t)+0.5*sin(2*PI*%s*%g*t)" % (f, f, detune))
    sub = "0.6*sin(2*PI*%s*t)" % _select(chord, [_hz(c[0] - 12) for c in chords])
    tremolo = "(0.8+0.2*sin(2*PI*0.23*t))"
    # arpeggio: one chord tone per step, cycling up through the chord an octave higher
    note = "mod(floor(t/%g),4)" % step
    arp_freqs = []
    for c in chords:
        arp_freqs.extend(_hz(n + 12) for n in c)
    arp_f = _select("(%s*4+%s)" % (chord, note), arp_freqs)
    arp_env = "exp(-5*mod(t,%g))*min(1,mod(t,%g)/0.01)" % (step, step)
    arp = "%s*(sin(2*PI*%s*t)+0.3*sin(4*PI*%s*t))" % (arp_env, arp_f, arp_f)
    return "0.055*%s*%s*(%s+%s)+0.06*%s" % (env, tremolo, "+".join(pad), sub, arp)


def builtin_input(name: str, duration: float, sample_rate: int = 44100) -> List[str]:
    """ffmpeg input arguments that generate a built-in track of ``duration`` seconds."""
    if name not in _PROGRESSIONS:
        raise ValueError("unknown built-in music %r (choose %s)" % (name, ", ".join(BUILTIN)))
    expr = generator_expr(name).replace(",", "\\,")
    return ["-f", "lavfi", "-i", "aevalsrc=%s:s=%d:d=%.3f" % (expr, sample_rate, duration + 0.5)]


def file_input(path: str) -> List[str]:
    """ffmpeg input arguments for a music file, looped so it always covers the video."""
    return ["-stream_loop", "-1", "-i", path]


#: Loudness every music bed is levelled to before ``volume`` is applied.
MUSIC_LUFS = -20.0


def mix_filter(voice: str, music: str, out: str, *, duration: float, volume: float = 0.5,
               builtin: bool = False, duck: bool = True) -> str:
    """Filter graph text: trims, fades and levels the music, ducks it under the voice and mixes.

    The music is first levelled to ``MUSIC_LUFS`` so ``volume`` means the same for a quiet
    ambient file and a loud mastered song: 1.0 keeps that level, 0.5 (default) is ~6 dB lower."""
    volume = max(0.0, float(volume))
    fade_out = max(0.0, duration - 2.5)
    chain = []
    music_chain = "[%s]aformat=sample_rates=44100:channel_layouts=stereo,atrim=0:%.3f,asetpts=N/SR/TB" % (
        music, duration)
    if builtin:
        # soft room: a short multi-tap echo and a gentle low-pass round the pure tones off
        music_chain += ",lowpass=f=3200,aecho=0.8:0.6:90|170|260:0.35|0.25|0.15"
    music_chain += ",loudnorm=I=%.1f:TP=-2:LRA=11,aresample=44100" % MUSIC_LUFS
    music_chain += ",volume=%.3f,afade=t=in:d=1.5,afade=t=out:st=%.3f:d=2.5[mus]" % (volume, fade_out)
    chain.append(music_chain)
    chain.append("[%s]aformat=sample_rates=44100:channel_layouts=stereo,asplit=2[vo][sc]" % voice)
    if duck:
        chain.append("[mus][sc]sidechaincompress=threshold=0.015:ratio=9:attack=25:release=450:"
                     "makeup=1[duck]")
        bed = "duck"
    else:
        chain.append("[sc]anullsink")
        bed = "mus"
    chain.append("[vo][%s]amix=inputs=2:duration=first:normalize=0,alimiter=limit=0.95[%s]" % (bed, out))
    return ";".join(chain)


def parse_music(value: Optional[str]) -> Tuple[Optional[str], bool]:
    """``--music`` value -> ``(source, builtin)``; ``None``/``none``/``off`` disables music."""
    if value is None or str(value).strip().lower() in ("", "none", "off", "no"):
        return None, False
    v = str(value).strip()
    return (v.lower(), True) if v.lower() in BUILTIN else (v, False)


def rms_db(samples: Sequence[float]) -> float:
    """Level of a block of samples in dBFS (used by tests)."""
    if not samples:
        return -120.0
    rms = math.sqrt(sum(s * s for s in samples) / len(samples))
    return 20 * math.log10(max(rms, 1e-6))
